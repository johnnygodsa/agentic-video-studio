def test_rules_see_original_context_around_word_table():
    """詞表先換成 token 會讓語境規則看不到原字(2026-10-21 修):規則改在原文上比對,再與詞表標注合併、重疊時詞表贏。"""
    # 規則詞「微調」的「微」被詞表標成 wéi,「調」仍要被規則標成 tiáo(修前只標到 [w][éi]調)
    t, hits = CT.apply_pron("這套系統微調的時候")
    assert t == "這套系統[w][éi][t][iáo]的時候" and "微調→[t][iáo]" in hits and "微" in hits, (t, hits)
    # 詞表贏:規則詞「角色」不存在,「角色得到」的角色維持詞表標注、得到 = dé
    t, _ = CT.apply_pron("你得到角色")
    assert t == "你[d][é]到[j][iǎo]色", t
    # 詞表詞與規則字相鄰:你得先 -> děi,遊戲照詞表
    t, _ = CT.apply_pron("這遊戲你得先改")
    assert t == "這遊[x][ì]你[d][ěi]先改", t
    # 覺得 = keep(仍輸出預設「的」,輕聲不用拼音 token),詞表詞「遊戲」不受影響
    t, _ = CT.apply_pron("他覺得這遊戲不錯")
    assert t == "他覺的這遊[x][ì]不錯", t
    # 兩邊的命中鍵都保留
    assert CT.pron_hits("這遊戲你得先改") == {"遊戲": "遊[x][ì]", "得→[d][ěi]": "[d][ěi]"}


def test_de_blacklist_rule():
    """得 děi/dé 規則改前字黑名單(2026-10-21):前字不是動詞/形容詞才標,詞表詞(遊戲、執行長、角色)不擋。"""
