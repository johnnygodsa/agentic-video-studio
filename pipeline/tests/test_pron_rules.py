def _check(ch, sent, target, py):
    i = sent.find(target)
    assert i >= 0, f"測試資料錯誤:{sent!r} 裡沒有 {target!r}"
    p = i + target.index(ch)
    got = {e[0]: e[2] for e in CT.rule_events(sent)}.get(p, "")
    want = tok(py)
    assert got == want, f"「{ch}」{sent!r} 第 {p} 字: 要 {want or '(不動)'},實際 {got or '(不動)'}"


def test_cases():
    bad, n = [], 0
    for ch, cases in CASES.items():
        for sent, target, py in cases:
            n += 1
            try:
                _check(ch, sent, target, py)
            except AssertionError as e:
                bad.append(str(e))
    assert not bad, f"{len(bad)}/{n} 句不符:\n" + "\n".join(bad)


def test_each_char_has_enough_cases():
    """規則檔每個字都要有 >=3 句測試,而且至少一句是預設讀音、每個非預設讀音各一句。"""
    short = {c: len(CASES.get(c, [])) for c in CT.RULE_CHARS if len(CASES.get(c, [])) < 3}
    assert not short, f"測試句不足 3 句: {short}"
    for ch, e in CT.RULE_CHARS.items():
        seen = {tok(py) for _s, _t, py in CASES[ch]}
        want = {r["py"] for r in e.get("rules", []) if r.get("py")}
        miss = [w for w in want if w not in seen]
        assert not miss, f"「{ch}」沒有測到的非預設讀音: {miss}"
        default = e["model_default"] if e.get("always") else ""
        assert default in seen or not CASES[ch], f"「{ch}」沒有預設讀音的測試句"


